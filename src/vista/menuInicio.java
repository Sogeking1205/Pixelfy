    private void btnAbrirLienzoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAbrirLienzoActionPerformed
        JFileChooser selector = new JFileChooser();
        selector.setDialogTitle("Abrir proyecto de Pixelfy");
        selector.setFileFilter(new FileNameExtensionFilter("Proyectos Pixelfy (*.txt)", "txt"));

        if (selector.showOpenDialog(this) == JFileChooser.APPROVE_OPTION) {
            File archivo = selector.getSelectedFile();

            // 1. Instanciamos GestorArchivos con la ruta seleccionada
            GestorArchivos gestor = new GestorArchivos(archivo.getAbsolutePath());

            // 2. Validamos que el archivo tenga el formato correcto antes de abrir
            if (!gestor.validarArchivo()) {
                JOptionPane.showMessageDialog(this, 
                    "El archivo seleccionado no es un proyecto válido de Pixelfy.", 
                    "Archivo inválido", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // 3. Creamos un Lienzo base y dejamos que el gestor lo rellene con los datos del .txt
            Lienzo lienzoCargado = new Lienzo(16, 16); // Tamaño temporal; cargarArchivo lo actualiza
            gestor.cargarArchivo(lienzoCargado);

            // 4. Abrimos el editor ya con el dibujo cargado (descomenta cuando crees VentanaEditor)
            // new VentanaEditor(lienzoCargado).setVisible(true);
            // this.dispose();

            JOptionPane.showMessageDialog(this, 
                "Proyecto cargado: " + lienzoCargado.getFilas() + "x" + lienzoCargado.getColumnas());
        }
    }//GEN-LAST:event_btnAbrirLienzoActionPerformed

    private void btnLienzoNuevoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLienzoNuevoActionPerformed
        String[] opciones = {"16x16", "32x32", "64x64"};

        String seleccion = (String) JOptionPane.showInputDialog(
                this,
                "Selecciona el tamaño del lienzo:",
                "Nuevo Lienzo - Pixelfy",
                JOptionPane.QUESTION_MESSAGE,
                null,
                opciones,
                opciones[1] // "32x32" por defecto
        );

        if (seleccion != null) {
            int dimension = Integer.parseInt(seleccion.split("x")[0]);

            // 1. Creamos el modelo Lienzo con las dimensiones elegidas
            Lienzo nuevoLienzo = new Lienzo(dimension, dimension);

            new VentanaPrincipal(nuevoLienzo).setVisible(true);
            this.dispose();

            JOptionPane.showMessageDialog(this, "Lienzo modelo creado: " + dimension + "x" + dimension);
        }
    }//GEN-LAST:event_btnLienzoNuevoActionPerformed

